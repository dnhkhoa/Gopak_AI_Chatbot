from __future__ import annotations

import json
import re
import sys
import unicodedata
from difflib import SequenceMatcher
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

CASES_PATH = ROOT / "evaluation" / "conversation_architecture_cases.json"
ARTIFACTS = ROOT / "artifacts"


def main() -> None:
    cases = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    utterances = _utterances(cases)
    dev = [item for item in utterances if item["set"] == "development"]
    holdout = [item for item in utterances if item["set"] == "holdout"]
    exact = _duplicates(utterances, "text")
    normalized = _duplicates([{**item, "normalized": _normalize(item["text"])} for item in utterances], "normalized")
    near = _near_duplicates(dev, holdout)
    leakage = _source_leakage(utterances)
    summary = {
        "case_count": len(cases),
        "utterance_count": len(utterances),
        "exact_duplicate_groups": len(exact),
        "normalized_duplicate_groups": len(normalized),
        "near_duplicate_pairs": len(near),
        "source_phrase_leakage_count": len(leakage),
        "integrity_passed": len(leakage) == 0,
        "holdout_independence_warning": len(near) > 0 or len(normalized) > 0,
    }
    output = {
        "summary": summary,
        "exact_duplicates": exact[:100],
        "normalized_duplicates": normalized[:100],
        "near_duplicates": near[:200],
        "source_phrase_leakage": leakage[:200],
        "oracle_independence": {
            "status": "PARTIAL",
            "note": "Conversation benchmark expected fields are static JSON expectations; response matching is performed by the runner. Numeric answers are not generated by the production functions.",
        },
    }
    ARTIFACTS.mkdir(exist_ok=True)
    (ARTIFACTS / "conversation_benchmark_integrity.json").write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=True, indent=2))


def _utterances(cases: list[dict[str, Any]]) -> list[dict[str, str]]:
    rows = []
    for case in cases:
        for index, turn in enumerate(case.get("turns", [])):
            rows.append(
                {
                    "case_id": str(case.get("id")),
                    "set": str(case.get("set")),
                    "category": str(case.get("category")),
                    "turn_index": str(index),
                    "text": str(turn.get("message") or ""),
                }
            )
    return rows


def _duplicates(items: list[dict[str, str]], key: str) -> list[dict[str, Any]]:
    groups: dict[str, list[dict[str, str]]] = {}
    for item in items:
        value = item[key]
        groups.setdefault(value, []).append(item)
    return [{"value": value, "items": rows} for value, rows in groups.items() if value and len(rows) > 1]


def _normalize(text: str) -> str:
    text = re.sub(r"#\d+", "#", text.lower())
    text = "".join(ch for ch in unicodedata.normalize("NFKD", text.replace("đ", "d")) if not unicodedata.combining(ch))
    text = re.sub(r"\d+", "0", text)
    text = re.sub(r"[^a-z0-9# ]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _near_duplicates(dev: list[dict[str, str]], holdout: list[dict[str, str]]) -> list[dict[str, Any]]:
    pairs = []
    dev_norm = [{**item, "normalized": _normalize(item["text"])} for item in dev]
    hold_norm = [{**item, "normalized": _normalize(item["text"])} for item in holdout]
    for left in dev_norm:
        for right in hold_norm:
            if left["category"] != right["category"]:
                continue
            score = SequenceMatcher(None, left["normalized"], right["normalized"]).ratio()
            if score >= 0.92:
                pairs.append({"dev": left, "holdout": right, "similarity": round(score, 4)})
    return pairs


def _source_leakage(utterances: list[dict[str, str]]) -> list[dict[str, str]]:
    source_files = list((ROOT / "src").rglob("*.py")) + list((ROOT / "backend").rglob("*.py"))
    source_texts = []
    for path in source_files:
        try:
            source_texts.append((path, _normalize(path.read_text(encoding="utf-8", errors="ignore"))))
        except OSError:
            continue
    leaks = []
    seen = set()
    for item in utterances:
        phrase = _normalize(item["text"])
        phrase = re.sub(r"\s+#$", "", phrase).strip()
        if len(phrase) < 18:
            continue
        for path, text in source_texts:
            if phrase in text:
                key = (item["case_id"], item["turn_index"], str(path))
                if key not in seen:
                    seen.add(key)
                    leaks.append({"case_id": item["case_id"], "turn_index": item["turn_index"], "phrase": item["text"], "file": str(path.relative_to(ROOT))})
    return leaks


if __name__ == "__main__":
    main()
